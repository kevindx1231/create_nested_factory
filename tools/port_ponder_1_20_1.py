"""Import Ponder exports from a read-only 1.21.1 checkout into this 1.20.1 project."""
import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import struct


TARGET = Path(__file__).resolve().parents[1]
PACKAGE = Path("src/main/java/com/createnestedfactory/create_nested_factory")
ASSETS = Path("src/main/resources/assets/create_nested_factory")


def read_nbt(data):
    stream = io.BytesIO(data)

    def number(fmt):
        return struct.unpack(">" + fmt, stream.read(struct.calcsize(">" + fmt)))[0]

    def string():
        return stream.read(number("H")).decode("utf-8")

    def payload(kind):
        if kind in range(1, 7):
            return number({1: "b", 2: "h", 3: "i", 4: "q", 5: "f", 6: "d"}[kind])
        if kind == 7:
            return stream.read(number("i"))
        if kind == 8:
            return string()
        if kind == 9:
            element_kind, size = number("b"), number("i")
            return element_kind, [payload(element_kind) for _ in range(size)]
        if kind == 10:
            result = {}
            while True:
                child_kind = number("b")
                if child_kind == 0:
                    return result
                name = string()
                result[name] = (child_kind, payload(child_kind))
        if kind in (11, 12):
            return [number("i" if kind == 11 else "q") for _ in range(number("i"))]
        raise ValueError(f"Unsupported NBT tag {kind}")

    kind, name = number("b"), string()
    result = kind, name, payload(kind)
    assert not stream.read(), "Unexpected trailing NBT data"
    return result


def write_nbt(root):
    stream = io.BytesIO()

    def number(fmt, value):
        stream.write(struct.pack(">" + fmt, value))

    def string(value):
        encoded = value.encode("utf-8")
        number("H", len(encoded))
        stream.write(encoded)

    def payload(kind, value):
        if kind in range(1, 7):
            number({1: "b", 2: "h", 3: "i", 4: "q", 5: "f", 6: "d"}[kind], value)
        elif kind == 7:
            number("i", len(value))
            stream.write(value)
        elif kind == 8:
            string(value)
        elif kind == 9:
            element_kind, elements = value
            number("b", element_kind)
            number("i", len(elements))
            for element in elements:
                payload(element_kind, element)
        elif kind == 10:
            for key, (child_kind, child) in value.items():
                number("b", child_kind)
                string(key)
                payload(child_kind, child)
            number("b", 0)
        elif kind in (11, 12):
            number("i", len(value))
            for element in value:
                number("i" if kind == 11 else "q", element)
        else:
            raise ValueError(f"Unsupported NBT tag {kind}")

    kind, name, value = root
    number("b", kind)
    string(name)
    payload(kind, value)
    return stream.getvalue()


def convert_items(kind, value):
    converted = 0
    if kind == 10:
        if value.get("id", (0, None))[0] == 8 and "count" in value:
            count_kind, count = value.pop("count")
            assert count_kind in (1, 2, 3, 4) and -128 <= count <= 127
            # Fail explicitly if a future export requires further component conversion.
            assert "components" not in value, "New item components require an explicit backport"
            value["Count"] = (1, count)
            converted += 1
        for child_kind, child in value.values():
            converted += convert_items(child_kind, child)
    elif kind == 9:
        child_kind, children = value
        for child in children:
            converted += convert_items(child_kind, child)
    return converted


def java_for_legacy(text):
    text = text.replace(
        "// Auto-generated by The Ponderer — do not edit; will be overwritten on next export.\n"
        "// 由思索者自动生成 — 请勿手动修改；下次导出时会被覆盖。",
        "// Imported from the 1.21.1 Ponderer export; adapted for Minecraft 1.20.1.\n"
        "// Re-import with tools/port_ponder_1_20_1.py; keep the source checkout read-only.")
    text = text.replace("ResourceLocation.fromNamespaceAndPath(", "new ResourceLocation(")
    text = text.replace("NbtAccounter.create(0x20000000L)", "new NbtAccounter(0x20000000L)")
    if "public final class GeneratedPonderSupport" in text:
        text = text.replace("import net.minecraft.nbt.TagParser;",
                            "import com.createnestedfactory.create_nested_factory.ponder.PonderNbt;")
        text = text.replace("TagParser.parseTag(", "PonderNbt.parseTag(")
        text = text.replace(
            "stack.set(net.minecraft.core.component.DataComponents.CUSTOM_DATA,\n"
            "                        net.minecraft.world.item.component.CustomData.of(tag));",
            "stack.setTag(tag);")
        before = """            net.minecraft.world.item.component.CustomData existing = copy.getOrDefault(
                net.minecraft.core.component.DataComponents.CUSTOM_DATA,
                net.minecraft.world.item.component.CustomData.EMPTY);
            CompoundTag stackTag = existing.copyTag();
            stackTag.merge(itemPatch.copy());
            copy.set(net.minecraft.core.component.DataComponents.CUSTOM_DATA,
                net.minecraft.world.item.component.CustomData.of(stackTag));"""
        after = """            CompoundTag stackTag = copy.getOrCreateTag();
            stackTag.merge(itemPatch.copy());"""
        assert before in text, "The exported item patch implementation changed"
        text = text.replace(before, after)
        assert "DataComponents" not in text and "CustomData" not in text
    if "GeneratedPonderNeoForgeClient" in text:
        text = text.replace("GeneratedPonderNeoForgeClient", "GeneratedPonderForgeClient")
        text = text.replace("net.neoforged.api.distmarker", "net.minecraftforge.api.distmarker")
        text = text.replace("net.neoforged.bus.api", "net.minecraftforge.eventbus.api")
        text = text.replace("import net.neoforged.fml.common.EventBusSubscriber;",
                            "import net.minecraftforge.fml.common.Mod;")
        text = text.replace("net.neoforged.fml.event.lifecycle", "net.minecraftforge.fml.event.lifecycle")
        text = text.replace('@EventBusSubscriber(modid = "create_nested_factory", value = Dist.CLIENT)',
                            '@Mod.EventBusSubscriber(modid = "create_nested_factory", value = Dist.CLIENT, bus = Mod.EventBusSubscriber.Bus.MOD)')
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    assert source != TARGET and (source / "gradle.properties").is_file()
    assert "minecraft_version=1.21.1" in (source / "gradle.properties").read_text(encoding="utf-8-sig")
    report = {"source": str(source), "java": [], "structures": {}, "translations": {}, "source_sha256": {}}

    def source_bytes(path):
        data = path.read_bytes()
        report["source_sha256"][path.relative_to(source).as_posix()] = hashlib.sha256(data).hexdigest()
        return data

    def write(relative, data):
        destination = TARGET / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            backup = TARGET / "migration/ponder-port/before" / relative
            if not backup.exists():
                backup.parent.mkdir(parents=True, exist_ok=True)
                backup.write_bytes(destination.read_bytes())
        destination.write_bytes(data)

    for path in sorted((source / PACKAGE / "ponder/generated").rglob("*.java")):
        relative = path.relative_to(source)
        if path.name == "GeneratedPonderNeoForgeClient.java":
            relative = relative.with_name("GeneratedPonderForgeClient.java")
        text = source_bytes(path).decode("utf-8-sig").replace("\r\n", "\n")
        write(relative, java_for_legacy(text).encode("utf-8"))
        report["java"].append(relative.as_posix())

    for path in sorted((source / ASSETS / "ponder").rglob("*.nbt")):
        original = gzip.decompress(source_bytes(path))
        root = read_nbt(original)
        assert write_nbt(root) == original, f"NBT codec changed {path.name}"
        converted = convert_items(root[0], root[2])
        root[2]["DataVersion"] = (3, 3465)
        encoded = write_nbt(root)
        assert read_nbt(encoded) == root
        write(path.relative_to(source), gzip.compress(encoded, mtime=0))
        report["structures"][path.name] = {"converted_item_stacks": converted}

    for language in ("en_us", "zh_cn"):
        relative = ASSETS / "lang" / f"{language}.json"
        incoming = json.loads(source_bytes(source / relative).decode("utf-8-sig"))
        current = json.loads((TARGET / relative).read_text(encoding="utf-8-sig"))
        translations = {key: value for key, value in incoming.items() if ".ponder." in key}
        current.update(translations)
        write(relative, (json.dumps(current, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
        report["translations"][language] = len(translations)

    output = TARGET / "migration/ponder-port/import-report.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for relative, expected in report["source_sha256"].items():
        assert hashlib.sha256((source / relative).read_bytes()).hexdigest() == expected
    print(f"Imported {len(report['java'])} Java files, {len(report['structures'])} NBT assets; "
          f"translations: {report['translations']}. Source files unchanged.")


if __name__ == "__main__":
    main()
